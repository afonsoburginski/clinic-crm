CREATE TABLE patients (
  clinic_id uuid NOT NULL, id uuid NOT NULL DEFAULT gen_random_uuid(), code bigint GENERATED BY DEFAULT AS IDENTITY,
  full_name text NOT NULL CHECK (length(trim(full_name)) >= 3), social_name text, birth_date date NOT NULL,
  document text, phone text, email text, status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','archived')),
  main_professional_id uuid, consent_data boolean NOT NULL DEFAULT false, consent_image boolean NOT NULL DEFAULT false,
  administrative_notes text, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(clinic_id,id), UNIQUE(clinic_id,code)
);
CREATE UNIQUE INDEX patients_document_unique ON patients(clinic_id, document) WHERE document IS NOT NULL;
CREATE INDEX patients_name_lookup ON patients(clinic_id, lower(full_name));

CREATE TABLE professionals (
 clinic_id uuid NOT NULL, id uuid NOT NULL DEFAULT gen_random_uuid(), name text NOT NULL, active boolean NOT NULL DEFAULT true,
 specialty_ids uuid[] NOT NULL DEFAULT '{}', schedule jsonb NOT NULL DEFAULT '[]', unavailabilities jsonb NOT NULL DEFAULT '[]',
 PRIMARY KEY(clinic_id,id), CHECK(cardinality(specialty_ids)>0)
);
ALTER TABLE patients ADD CONSTRAINT patient_main_professional_fk FOREIGN KEY(clinic_id,main_professional_id) REFERENCES professionals(clinic_id,id);

CREATE TABLE guardians (
 clinic_id uuid NOT NULL, id uuid NOT NULL DEFAULT gen_random_uuid(), full_name text NOT NULL, document text, phone text NOT NULL,
 email text, created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(clinic_id,id)
);
CREATE TABLE patient_guardians (
 clinic_id uuid NOT NULL, id uuid NOT NULL DEFAULT gen_random_uuid(), patient_id uuid NOT NULL, guardian_id uuid NOT NULL,
 relationship text NOT NULL, is_legal_guardian boolean NOT NULL DEFAULT false, can_schedule boolean NOT NULL DEFAULT false,
 can_receive_documents boolean NOT NULL DEFAULT false, is_primary_contact boolean NOT NULL DEFAULT false, restrictions text,
 PRIMARY KEY(clinic_id,id), UNIQUE(clinic_id,patient_id,guardian_id),
 FOREIGN KEY(clinic_id,patient_id) REFERENCES patients(clinic_id,id), FOREIGN KEY(clinic_id,guardian_id) REFERENCES guardians(clinic_id,id)
);
CREATE UNIQUE INDEX one_primary_guardian ON patient_guardians(clinic_id,patient_id) WHERE is_primary_contact;

CREATE TABLE appointments (
 clinic_id uuid NOT NULL, id uuid NOT NULL DEFAULT gen_random_uuid(), kind text NOT NULL CHECK(kind IN ('appointment','block')),
 title text, patient_id uuid, professional_id uuid NOT NULL, service_id uuid, room_id uuid,
 starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL, status text NOT NULL CHECK(status IN ('requested','pending','confirmed','in_progress','completed','cancelled','no_show')),
 notes text, cancel_reason text, created_by text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(clinic_id,id), CHECK(ends_at>starts_at), FOREIGN KEY(clinic_id,patient_id) REFERENCES patients(clinic_id,id),
 FOREIGN KEY(clinic_id,professional_id) REFERENCES professionals(clinic_id,id)
);
CREATE INDEX appointments_agenda ON appointments(clinic_id,professional_id,starts_at) WHERE status NOT IN ('cancelled','no_show');
